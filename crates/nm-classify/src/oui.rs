pub fn lookup_vendor(mac: &MacAddress) -> Option<String> {
    let prefix = format!("{:02x}:{:02x}:{:02x}", mac.bytes()[0], mac.bytes()[1], mac.bytes()[2]);
    VENDORS
        .iter()
        .find(|(p, _)| *p == prefix)
        .map(|(_, name)| name.to_string())
}
